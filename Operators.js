//----Modulus operator
let z=4%2
console.log(z)
//pre-increment,post-increment,pre-decrement,post-decrement

//post-increment
let x=10
console.log(x++) //post-increment ->x ->++
console.log(x)

//pre-increment
let y=20
console.log(++y) //pre-increment ->++ ->x

//pre-decrement
let a=30
console.log(--a) //pre-decrement ->-- ->x

//post-decrement
let b=40
console.log(b--) //post-decrement ->x ->--
console.log(b)
